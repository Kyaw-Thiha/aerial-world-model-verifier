"""Scene families for the simulated labelled set (Track I, Step 2).

One description, consumed by every renderer adapter, in the format the spike established:

    {seed, family, ground_m, checker_m, ground_colors, sun_*, sky_strength, objects[]}

with each object ``{kind, x, y, w, d, h, color}`` and ``kind`` in
``block`` (a box, buildings and containers), ``tree`` (a cone), ``hedge`` (a long low box),
``road`` (a flat box at ground level) and ``water`` (a large plane below the ground level).

The five families exist because the split is by scene: development uses ``urban_checker``,
``forest_ridge`` and ``industrial``; ``field_settlement`` and ``coastal_cliff`` are held out
and never used for any development decision (see ``configs/sim_prereg.yaml``). The families
differ in what the gravity estimator sees — checker texture versus canopy versus sheds and
roads versus hedgerows versus a water horizon — which is the point: a tilt reader that only
works on one of them is a finding, not a bug.

``src/sim/scene.py::layout`` stays as it was: the spike's renders (reports/I01) were made with
it and are not regenerated by this module.
"""
from __future__ import annotations

import numpy as np

E3 = (0.0, 0.0, 1.0)


def _base(family: str, seed: int) -> dict:
    return {"seed": int(seed), "family": family, "ground_m": 800.0, "checker_m": 20.0,
            "ground_colors": [[0.10, 0.13, 0.08], [0.26, 0.24, 0.18]],
            "sun_energy": 1.6, "sun_elevation_deg": 45.0, "sun_azimuth_deg": 35.0,
            "sky_strength": 0.5, "objects": []}


def _ring(rng, n, r_min, r_max):
    ang = rng.uniform(0, 2 * np.pi, n)
    rad = rng.uniform(r_min, r_max, n)
    return rad * np.cos(ang), rad * np.sin(ang)


def _add(lay, kind, x, y, w, d, h, color):
    lay["objects"].append({"kind": kind, "x": float(x), "y": float(y), "w": float(w),
                           "d": float(d), "h": float(h), "color": [float(c) for c in color]})


def urban_checker(seed: int) -> dict:
    """Blocks on a checker ground: vertical edges and a hard horizon."""
    rng = np.random.default_rng(seed)
    lay = _base("urban_checker", seed)
    lay["checker_m"] = 20.0
    lay["ground_colors"] = [[0.10, 0.13, 0.08], [0.26, 0.24, 0.18]]
    x, y = _ring(rng, 48, 25.0, 140.0)
    for i in range(48):
        _add(lay, "block", x[i], y[i], rng.uniform(4, 12), rng.uniform(4, 12),
             rng.uniform(4, 30), np.array([0.42, 0.40, 0.36]) * rng.uniform(0.8, 1.15))
    x, y = _ring(rng, 60, 18.0, 160.0)
    for i in range(60):
        _add(lay, "tree", x[i], y[i], rng.uniform(0.9, 1.8), rng.uniform(0.9, 1.8),
             rng.uniform(4, 12), (0.10, 0.22, 0.08))
    return lay


def forest_ridge(seed: int) -> dict:
    """Canopy everywhere, a low ridge on the horizon, a dirt-toned ground."""
    rng = np.random.default_rng(seed)
    lay = _base("forest_ridge", seed)
    lay["checker_m"] = 26.0
    lay["ground_colors"] = [[0.09, 0.11, 0.06], [0.16, 0.15, 0.10]]
    lay["sun_elevation_deg"] = 38.0
    lay["sun_azimuth_deg"] = 120.0
    # trees start well outside the flight's typical radius so the ground and the ridge stay
    # visible: an all-canopy frame is a legitimate but unrepresentative view
    x, y = _ring(rng, 520, 25.0, 200.0)
    for i in range(520):
        h = rng.uniform(6, 18)
        _add(lay, "tree", x[i], y[i], h * 0.20, h * 0.20, h,
             np.array([0.08, 0.18, 0.06]) * rng.uniform(0.7, 1.3))
    # a ridge: a ring of wide, low cones far out
    for i in range(24):
        ang = 2 * np.pi * i / 24 + rng.uniform(-0.05, 0.05)
        rad = rng.uniform(300.0, 420.0)
        _add(lay, "tree", rad * np.cos(ang), rad * np.sin(ang),
             rng.uniform(150, 280), rng.uniform(150, 280), rng.uniform(25, 55),
             (0.12, 0.14, 0.13))
    return lay


def industrial(seed: int) -> dict:
    """Long sheds, containers and service roads: strong straight lines at two scales."""
    rng = np.random.default_rng(seed)
    lay = _base("industrial", seed)
    lay["checker_m"] = 30.0
    lay["ground_colors"] = [[0.18, 0.18, 0.18], [0.28, 0.28, 0.27]]
    lay["sun_elevation_deg"] = 52.0
    for i in range(10):                       # sheds
        ang = 2 * np.pi * i / 10 + rng.uniform(-0.2, 0.2)
        rad = rng.uniform(35, 130)
        _add(lay, "block", rad * np.cos(ang), rad * np.sin(ang),
             rng.uniform(25, 60), rng.uniform(10, 22), rng.uniform(5, 9),
             (0.55, 0.56, 0.58))
    x, y = _ring(rng, 90, 20, 150)             # containers
    for i in range(90):
        _add(lay, "block", x[i], y[i], rng.uniform(6, 12), rng.uniform(2.4, 2.6),
             rng.uniform(2.4, 2.6), np.array([0.45, 0.20, 0.12]) * rng.uniform(0.8, 1.4))
    for i in range(6):                         # service roads
        ang = np.pi * i / 6
        _add(lay, "road", 0.0, 0.0, 400.0, 7.0, 0.02, (0.10, 0.10, 0.11))
        lay["objects"][-1]["rotate_z_deg"] = float(np.degrees(ang))
    return lay


def field_settlement(seed: int) -> dict:
    """Open fields, hedgerows at field boundaries, a few houses: a horizon with structure."""
    rng = np.random.default_rng(seed)
    lay = _base("field_settlement", seed)
    lay["checker_m"] = 40.0
    lay["ground_colors"] = [[0.22, 0.26, 0.10], [0.34, 0.33, 0.16]]
    lay["sun_elevation_deg"] = 30.0
    lay["sun_azimuth_deg"] = 200.0
    for i in range(14):                        # hedgerows
        ang = 2 * np.pi * i / 14 + rng.uniform(-0.1, 0.1)
        rad = rng.uniform(40, 220)
        _add(lay, "hedge", rad * np.cos(ang), rad * np.sin(ang),
             rng.uniform(60, 200), rng.uniform(2.0, 4.0), rng.uniform(1.5, 3.0),
             (0.10, 0.16, 0.07))
        lay["objects"][-1]["rotate_z_deg"] = float(np.degrees(ang + np.pi / 2))
    x, y = _ring(rng, 18, 30, 180)             # houses
    for i in range(18):
        _add(lay, "block", x[i], y[i], rng.uniform(8, 16), rng.uniform(6, 12),
             rng.uniform(4, 9), np.array([0.62, 0.58, 0.50]) * rng.uniform(0.85, 1.1))
    x, y = _ring(rng, 120, 12, 240)            # scattered trees
    for i in range(120):
        h = rng.uniform(5, 14)
        _add(lay, "tree", x[i], y[i], h * 0.22, h * 0.22, h, (0.10, 0.20, 0.07))
    for i in range(20):                        # distant hills
        ang = 2 * np.pi * i / 20
        rad = rng.uniform(300, 430)
        _add(lay, "tree", rad * np.cos(ang), rad * np.sin(ang),
             rng.uniform(160, 300), rng.uniform(160, 300), rng.uniform(15, 40),
             (0.16, 0.17, 0.15))
    return lay


def coastal_cliff(seed: int) -> dict:
    """A land strip with water beyond it: the horizon is a water line, not a ground plane.

    The land is a finite plane (``ground_m`` = 300 m, i.e. 150 m around the camera) with water
    three metres lower and extending to 4 km, so a level camera sees land below and water out
    to the horizon on every bearing where the land ends. Without the finite land the water was
    invisible at flight altitude, which is exactly the kind of "family" that exists in name
    only and was caught by rendering a frame instead of trusting the description.
    """
    rng = np.random.default_rng(seed)
    lay = _base("coastal_cliff", seed)
    lay["ground_m"] = 300.0
    lay["checker_m"] = 24.0
    lay["ground_colors"] = [[0.16, 0.18, 0.10], [0.34, 0.31, 0.22]]
    lay["sun_elevation_deg"] = 22.0
    lay["sun_azimuth_deg"] = 250.0
    _add(lay, "water", 0.0, 0.0, 4000.0, 4000.0, 0.0, (0.02, 0.09, 0.16))
    lay["objects"][-1]["z"] = -3.0
    # one cliff wall along +y, so the view alternates between open water and a hard edge
    _add(lay, "block", 0.0, 150.0, 320.0, 22.0, 16.0, (0.33, 0.29, 0.23))
    # rocks along the shoreline
    for i in range(70):
        ang = rng.uniform(0, 2 * np.pi)
        rad = rng.uniform(120.0, 170.0)
        _add(lay, "block", rad * np.cos(ang), rad * np.sin(ang),
             rng.uniform(6, 22), rng.uniform(6, 22), rng.uniform(2, 9),
             (0.24, 0.22, 0.19))
    # vegetation inland
    x, y = _ring(rng, 140, 20.0, 140.0)
    for i in range(140):
        h = rng.uniform(3, 11)
        _add(lay, "tree", x[i], y[i], h * 0.3, h * 0.3, h,
             np.array([0.12, 0.17, 0.08]) * rng.uniform(0.8, 1.2))
    return lay


FAMILIES = {
    "urban_checker": urban_checker,
    "forest_ridge": forest_ridge,
    "industrial": industrial,
    "field_settlement": field_settlement,
    "coastal_cliff": coastal_cliff,
}


def layout(family: str, seed: int = 7) -> dict:
    """Resolve a family and a seed into the renderer-neutral scene description."""
    if family not in FAMILIES:
        raise KeyError(f"unknown scene family {family!r}; have {sorted(FAMILIES)}")
    return FAMILIES[family](int(seed))


if __name__ == "__main__":                       # a quick census, no Blender needed
    for name in FAMILIES:
        lay = layout(name, 101)
        kinds = {}
        for o in lay["objects"]:
            kinds[o["kind"]] = kinds.get(o["kind"], 0) + 1
        print(f"{name:18s} objects={len(lay['objects']):4d} {kinds}")
