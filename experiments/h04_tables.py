"""H04: generate the report tables and the summary lines from the scored campaign.

    PYTHONPATH=. pixi run -e gpu python experiments/h04_tables.py

Writes ``report_candidates/h04_tables.tex`` and ``results/h04/summary.md``.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARMS = {"A_flatness": "A, flatness", "B_level": "B, level", "C_mirrored_roll": "C, mirrored"}


def pct(k, n):
    return f"{100.0 * k / n:.0f}\\,\\% ({k}/{n})" if n else "--"


def main() -> int:
    d = json.loads((ROOT / "results/h04/scored_main.json").read_text())
    rows = json.loads((ROOT / "results/h04/scored_main_rows.json").read_text())
    tex = ["% generated by experiments/h04_tables.py from results/h04/scored_main.json",
           "\\begin{table}[t]", "\\footnotesize",
           "\\begin{tabular}{lrrrrrrr}", "\\toprule",
           "arm & clips & testable & accepted & coherence flag & R2 flag & median residual & depicted/required \\\\",
           " & & & & (of testable) & (of testable) & (deg) & (median) \\\\", "\\midrule"]
    lines = []
    for arm, label in ARMS.items():
        b = d["per_arm"][arm]
        tex.append(f"{label} & {b['n']} & {b['testable_k']} & {b['accepted_k']} & "
                   f"{pct(b['flag_coh_k'], b['testable_k'])} & "
                   f"{pct(b['flag_r2_k'], b['testable_k'])} & "
                   f"{b['median_residual_deg']:.2f} & "
                   f"{b['depicted_over_required_median']:.2f} \\\\")
        lines.append(
            f"* **{label}**: {b['n']} clips, {b['testable_k']} testable "
            f"({', '.join(f'{k}: {v}' for k, v in b['abstention_reasons'].items()) or 'no abstentions'}), "
            f"{b['accepted_k']} accepted; coherence flag {pct(b['flag_coh_k'], b['testable_k'])}, "
            f"R2 flag {pct(b['flag_r2_k'], b['testable_k'])}, median residual "
            f"{b['median_residual_deg']:.2f} deg, depicted/required median "
            f"{b['depicted_over_required_median']:.2f}, magnitude-consistent "
            f"{b['magnitude_consistent_k']}/{b['magnitude_consistent_n']}.")
    tex += ["\\bottomrule", "\\end{tabular}",
            "\\caption{SolarWM continuous-attitude campaign, frozen tiers.  Accept means testable "
            "and not flagged by the coherence tier; every rate carries its denominator.}",
            "\\label{tab:h04-arms}", "\\end{table}", ""]

    # per family / peak, arm A
    tex += ["\\begin{table}[t]", "\\footnotesize",
            "\\begin{tabular}{llrrrr}", "\\toprule",
            "family & peak (deg) & clips & testable & accepted & coherence flag \\\\", "\\midrule"]
    by = {}
    for r in rows:
        if r["arm"] != "A_flatness":
            continue
        by.setdefault((r["family"], r["requested_peak"]), []).append(r)
    for (fam, peak), items in sorted(by.items()):
        test = [i for i in items if i["testable"]]
        acc = [i for i in items if i["accepted"]]
        tex.append(f"{fam} & {peak:.0f} & {len(items)} & {len(test)} & {len(acc)} & "
                   f"{pct(sum(i['flagged_coh'] for i in test), len(test))} \\\\")
    tex += ["\\bottomrule", "\\end{tabular}",
            "\\caption{Arm A by path family and requested peak bank.}", "\\label{tab:h04-grid}",
            "\\end{table}", ""]

    # sampling
    s = d["sample_spread"]
    b3 = d["best_of_3"]
    tex += ["\\begin{table}[t]", "\\footnotesize",
            "\\begin{tabular}{lr}", "\\toprule", "quantity & value \\\\", "\\midrule",
            f"paths with 3 draws & {s['n_paths']} \\\\",
            f"median seed sd of the residual & {s['median_sd_deg']:.2f} deg \\\\",
            f"median seed range of the residual & {s['median_range_deg']:.2f} deg \\\\",
            f"oracle best-of-3 reduction, median & {b3['median_reduction_deg']:.2f} deg \\\\",
            f"paths flipping from flagged to accepted & {b3['paths_flipping_to_accept']} \\\\",
            "\\bottomrule", "\\end{tabular}",
            "\\caption{Sample variance and the oracle best-of-3, arm A.  The three draws are "
            "validation draws, not a seed knob.}", "\\label{tab:h04-sampling}", "\\end{table}", ""]

    lines.append(f"* **Sample variance (arm A)**: median residual sd across draws "
                 f"{s['median_sd_deg']:.2f} deg (range {s['median_range_deg']:.2f}); oracle "
                 f"best-of-3 reduction {b3['median_reduction_deg']:.2f} deg; "
                 f"{b3['paths_flipping_to_accept']} of {b3['n_paths']} paths flip.")
    y = d.get("yaw_control", {})
    if y:
        lines.append(f"* **Yaw control**: {y.get('testable_k', 0)}/{y.get('n', 0)} testable, "
                     f"coherence flag {pct(y.get('flag_coh_k', 0), y.get('testable_k', 0))}.")
    nul = d.get("null_same_arm", [])
    if nul:
        lines.append(f"* **Same-arm null**: {sum(n['flagged'] for n in nul)}/{len(nul)} "
                     f"draw pairs flagged.")
    (ROOT / "report_candidates/h04_tables.tex").write_text("\n".join(tex) + "\n")
    (ROOT / "results/h04/summary.md").write_text("\n".join(["# H04 summary"] + lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
