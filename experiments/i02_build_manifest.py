"""Assemble the Track I dataset manifest and keep ``docs/DATA.md`` in step (Step 2).

The render app writes one manifest row per clip to the Modal volume
(``/vol/i02/clips/<clip_id>/manifest_row.json`` plus ``/vol/i02/last_batch.json`` for the most
recent batch). This script pulls those rows, merges them into ``results/i02/manifest.csv``
(git), verifies that each R2 object exists and hashes to what the row claims, and rewrites the
Track I block of ``docs/DATA.md`` between its markers.

    python experiments/i02_build_manifest.py --pull            # after a render batch
    python experiments/i02_build_manifest.py --verify          # re-hash from R2
    python experiments/i02_build_manifest.py --docs            # rewrite docs/DATA.md block
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "results/i02/manifest.csv"
TABLE = ROOT / "configs/sim_splits_frozen.json"
DOCS = ROOT / "docs/DATA.md"
BEGIN = "<!-- track-i-dataset:begin (generated by experiments/i02_build_manifest.py) -->"
END = "<!-- track-i-dataset:end -->"

FIELDS = ["clip_id", "split", "family", "scene_seed", "maneuver", "uptilt_deg", "label",
          "violation", "defect_family", "magnitude_deg", "magnitude_unit", "defect_magnitude",
          "interval_start_s", "interval_end_s", "interval_fraction", "duration_s", "n_frames",
          "n_gt", "peak_tilt_req_deg", "median_tilt_req_deg", "peak_thrust_ratio",
          "params_json", "renderer", "engine", "samples", "r2_video", "r2_gt",
          "sha256_video", "sha256_gt", "bytes_video", "bytes_gt", "commit", "generated_utc",
          "status"]


def _modal(*args: str) -> None:
    """Run the Modal CLI from the project's pixi env (the only place it is installed)."""
    pixi = Path.home() / "Documents/Projects/aerial-world-model-verifier/.pixi/envs/default/bin/modal"
    exe = str(pixi) if pixi.is_file() else "modal"
    subprocess.run([exe, *args], check=True, cwd=ROOT)


def pull() -> list[dict]:
    """Download the most recent batch's rows and merge them into the manifest."""
    # `modal volume get` fails if the destination exists (the CLI's documented quirk in
    # docs/DATA.md), so remove it first
    Path("/tmp/i02_last_batch.json").unlink(missing_ok=True)
    _modal("volume", "get", "awmv-i-data", "i02/last_batch.json", "/tmp/i02_last_batch.json")
    batch = json.loads(Path("/tmp/i02_last_batch.json").read_text())
    rows = batch["rows"]
    existing = {}
    if MANIFEST.is_file():
        with MANIFEST.open() as fh:
            for r in csv.DictReader(fh):
                existing[r["clip_id"]] = r
    for r in rows:
        row = {k: r.get(k, "") for k in FIELDS}
        # a row that was never published must not carry a volume/tmp path in the R2 columns
        if not str(row.get("r2_video", "")).startswith("track-i/"):
            row["r2_video"] = row["r2_gt"] = ""
        existing[r["clip_id"]] = row
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    with MANIFEST.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        for cid in sorted(existing):
            w.writerow({k: existing[cid].get(k, "") for k in FIELDS})
    print(f"manifest: {len(existing)} rows ({len(rows)} from this batch) -> {MANIFEST}")
    return rows


def verify() -> dict:
    """Re-hash every uploaded object from R2 and compare with the manifest."""
    from src.utils import r2 as r2mod

    if not MANIFEST.is_file():
        raise SystemExit("no manifest to verify")
    env = r2mod.load_env()
    cli = r2mod.client(env)
    ok = bad = missing = 0
    problems = []
    with MANIFEST.open() as fh:
        for r in csv.DictReader(fh):
            if r.get("status") != "ok":
                continue
            for key_field, hash_field in (("r2_video", "sha256_video"), ("r2_gt", "sha256_gt")):
                key = r[key_field]
                try:
                    body = cli.get_object(Bucket=env["R2_BUCKET"], Key=key)["Body"].read()
                except Exception as exc:                     # noqa: BLE001 - report, do not retry
                    missing += 1
                    problems.append((r["clip_id"], key, repr(exc)[:120]))
                    continue
                if hashlib.sha256(body).hexdigest() == r[hash_field]:
                    ok += 1
                else:
                    bad += 1
                    problems.append((r["clip_id"], key, "sha256 mismatch"))
    print(f"verified {ok} objects, {bad} mismatched, {missing} missing")
    for p in problems[:10]:
        print("  ", p)
    return {"ok": ok, "bad": bad, "missing": missing, "problems": problems}


def docs() -> None:
    """Rewrite the generated block in docs/DATA.md from the manifest and the frozen table."""
    table = json.loads(TABLE.read_text())
    rows = []
    if MANIFEST.is_file():
        with MANIFEST.open() as fh:
            rows = [r for r in csv.DictReader(fh) if r.get("status") == "ok"]
    table_sha = hashlib.sha256(TABLE.read_bytes()).hexdigest()
    prereg_sha = hashlib.sha256((ROOT / "configs/sim_prereg.yaml").read_bytes()).hexdigest()
    by_split = {}
    for r in rows:
        by_split.setdefault(r["split"], []).append(r)
    lines = [BEGIN]
    lines += [
        "### Track I — simulated labelled flight set (`track-i/` on R2)",
        "",
        f"Pre-registration `configs/sim_prereg.yaml` sha256 `{prereg_sha[:16]}…`; frozen clip table "
        f"`configs/sim_splits_frozen.json` sha256 `{table_sha[:16]}…` "
        f"({len(table['clips'])} clips: 200 development, 100 held-out).",
        "",
        "Scene families are split before any clip existed and never mixed: "
        "**development** `urban_checker`, `forest_ridge`, `industrial` (seeds 101-106); "
        "**held-out** `field_settlement`, `coastal_cliff` (seeds 201-206). A held-out clip is "
        "rendered with the batch but is not scored until the development pass is committed.",
        "",
        f"Objects on R2: `track-i/videos/<split>/<family>/<clip_id>.mp4` (H.264 CRF 18, 30 fps), "
        f"`track-i/gt/<clip_id>.npz` (250 Hz truth: position, velocity, acceleration, yaw, "
        f"commanded and rendered attitude, required and depicted lean/tilt, defect mask). "
        f"Manifest: `results/i02/manifest.csv` (one row per clip, sha256 of both objects, the "
        f"exact violation interval and the development/held-out label).",
        "",
    ]
    if rows:
        lines += ["| split | clips on R2 | families | defect families | frames |",
                  "| --- | --- | --- | --- | --- |"]
        for split in ("dev", "heldout"):
            sub = by_split.get(split, [])
            if not sub:
                continue
            fams = sorted({r["family"] for r in sub})
            defs = sorted({r["defect_family"] for r in sub})
            frames = sum(int(r["n_frames"]) for r in sub)
            lines.append(f"| {split} | {len(sub)} | {', '.join(fams)} | {', '.join(defs)} | {frames} |")
        lines.append("")
        lines.append("First usable batch: the clips listed in `results/i02/manifest.csv`; each "
                     "row carries the interval `[interval_start_s, interval_end_s]` and the "
                     "magnitude in degrees, so a detector (Track G2) and a clip-level verdict "
                     "(Tracks F2, G2) can both read the same labels.")
    else:
        lines += ["_No clip has been uploaded yet._"]
    lines.append(END)
    block = "\n".join(lines)
    text = DOCS.read_text()
    if BEGIN in text and END in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):]
        DOCS.write_text(head + block + tail)
    else:
        DOCS.write_text(text.rstrip() + "\n\n" + block + "\n")
    print(f"docs: rewrote the Track I block in {DOCS.relative_to(ROOT)} "
          f"({len(rows)} clips)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pull", action="store_true")
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--docs", action="store_true")
    args = ap.parse_args()
    did = False
    if args.pull:
        pull()
        did = True
    if args.verify:
        verify()
        did = True
    if args.docs:
        docs()
        did = True
    if not did:
        ap.print_help()
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
